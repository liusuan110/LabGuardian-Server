# CLI
# ---------------------------------------------------------------------------


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pdf", required=True, type=Path, help="path to the source PDF")
    parser.add_argument("--document-id", required=True, help="stable document id (becomes chunk_id prefix)")
    parser.add_argument("--out", required=True, type=Path, help="output DatasheetDocument JSON path")
    parser.add_argument("--title", default="", help="document title; falls back to existing JSON or document_id")
    parser.add_argument(
        "--part-numbers",
        nargs="*",
        default=[],
        help="part numbers / aliases for keyword expansion",
    )
    parser.add_argument(
        "--backend",
        default="auto",
        choices=["auto", "mineru", "magic_pdf", "pypdf"],
        help="parse backend (auto picks the best available)",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="discard existing JSON entirely instead of merging",
    )
    parser.add_argument("--verbose", "-v", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_arg_parser().parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(levelname)s %(name)s: %(message)s",
    )

    pdf_path: Path = args.pdf.resolve()
    if not pdf_path.exists():
        logger.error("pdf not found: %s", pdf_path)
        return 2

    backend = resolve_backend(args.backend)
    logger.info("using backend=%s for %s", backend.name, pdf_path.name)

    out_path: Path = args.out.resolve()
    asset_dir = out_path.parent / "assets" / args.document_id
    new_chunks = backend.parse(pdf_path, args.document_id, asset_dir)
    logger.info("backend produced %d chunks", len(new_chunks))

    existing = load_existing(out_path)
    try:
        source_path = str(pdf_path.relative_to(REPO_ROOT))
    except ValueError:
        source_path = str(pdf_path)

    document = merge_document(
        existing,
        document_id=args.document_id,
        title=args.title,
        part_numbers=list(args.part_numbers),
        source_path=source_path,
        new_chunks=new_chunks,
        overwrite=args.overwrite,
    )

    write_document(out_path, document)
    logger.info(
        "wrote %s — %d total chunks (modalities: %s)",
        out_path.relative_to(REPO_ROOT) if out_path.is_relative_to(REPO_ROOT) else out_path,
        len(document.chunks),
        ",".join(sorted({c.modality for c in document.chunks})),
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
