"""Build-time PDF -> DatasheetDocument JSON ingest pipeline.

This script is intentionally **not** part of the LabGuardian runtime. It runs
on a developer / CI machine, parses one or more datasheet PDFs, and writes
``DatasheetDocument`` JSON files into ``knowledge/datasheets/``. The board
afterwards only consumes the produced JSON + assets — it never imports MinerU,
Magic-PDF, or any layout/OCR model.

Three backends, in priority order:

1. ``mineru`` — full multimodal parse (text / table / figure / formula /
   layout). Requires ``pip install '.[ingest]'``; pulls model weights on first
   run. Produces the richest output.
2. ``magic_pdf`` — same project, older package name. Compatible adapter kept
   here so older environments still work.
3. ``pypdf`` — text-only fallback that ships in the runtime deps. No external
   downloads, no GPU. Used today when MinerU isn't installed; produces real
   per-page text chunks but cannot extract figures / tables.

Merge semantics:

- If the target JSON already exists, the script preserves manually authored
  figure / table / schematic / waveform chunks and replaces only text chunks
  with newly extracted content. Document-level metadata (title, part_numbers,
  source_path) is taken from the existing JSON if present, else from CLI args.
- ``--overwrite`` discards the existing file entirely.

CLI examples
============

::

    python scripts/ingest_datasheets.py \
        --pdf knowledge_base/C695838_555定时器-计时器_NE555DR_规格书_WJ1799212.PDF \
        --document-id ne555 \
        --out knowledge/datasheets/ne555.json

    python scripts/ingest_datasheets.py \
        --pdf knowledge_base/sn74ls74a.pdf \
        --document-id sn74ls74a \
        --title "SN74LS74A 双 D 触发器" \
        --part-numbers SN74LS74A SN74LS74AN \
        --out knowledge/datasheets/sn74ls74a.json \
        --backend pypdf
"""

from __future__ import annotations

import argparse
import importlib
import json
import logging
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Iterable

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from app.schemas.kb import DatasheetChunk, DatasheetDocument  # noqa: E402

logger = logging.getLogger("ingest_datasheets")

# Token regex matches CJK characters individually and Latin/digit runs together.
_TOKEN_PATTERN = re.compile(r"[A-Za-z0-9]+|[一-鿿]")
_STOPWORDS = {
    "的", "是", "在", "和", "或", "与", "及", "为", "了", "也", "可", "见", "如",
    "the", "and", "or", "of", "to", "for", "in", "on", "with", "by", "is", "are",
    "this", "that", "be", "as", "an", "a", "at", "from",
}


def _tokenize(text: str) -> list[str]:
    return [tok.lower() for tok in _TOKEN_PATTERN.findall(text or "")]


def _top_keywords(text: str, limit: int = 8) -> list[str]:
    counts = Counter(
        tok
        for tok in _tokenize(text)
        if len(tok) > 1 and tok not in _STOPWORDS
    )
    return [tok for tok, _ in counts.most_common(limit)]


